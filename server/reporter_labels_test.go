package server

import (
	"database/sql"
	"reflect"
	"testing"

	"github.com/Autumn-27/artex/db"
)

func TestReporterLabelsMigrationPG(t *testing.T) {
	dsn, _, err := db.DSN()
	if err != nil {
		t.Skipf("no database config (%v) — skipping", err)
	}
	conn, err := sql.Open("pgx", dsn)
	if err != nil {
		t.Fatal(err)
	}
	pg := &db.DB{DB: conn}
	t.Cleanup(func() { _ = pg.Close() })
	pg.SetMaxOpenConns(1)
	if err := pg.PingContext(t.Context()); err != nil {
		t.Skipf("postgres unavailable (%v) — skipping", err)
	}
	// Copy the existing schema without running application initialization.
	for _, table := range []string{"agents", "settings", "agent_prompts", "agent_triggers", "tools"} {
		if _, err := pg.Exec(`CREATE TEMP TABLE ` + table + ` (LIKE ` + table + ` INCLUDING ALL)`); err != nil {
			t.Fatal(err)
		}
	}
	// LIKE copies serial defaults; give fixture inserts private temporary identities.
	for _, table := range []string{"agents", "agent_prompts", "agent_triggers"} {
		if _, err := pg.Exec(`ALTER TABLE ` + table + ` ALTER COLUMN id DROP DEFAULT,
			ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY`); err != nil {
			t.Fatal(err)
		}
	}
	s := &Server{m: &Manager{pg: pg}}
	const oldName = "보고서 작성"
	const oldDescription = "취약점 상세 보고서 작성: 취약점을 발견하면 자동으로 트리거되어, 증거와 실행 과정을 조회한 뒤 Markdown 보고서를 작성해 해당 취약점에 기록합니다."
	for _, tc := range []struct {
		name, storedName, storedDescription, wantName, wantDescription string
		fresh, deleted                                                 bool
	}{
		{name: "fresh", fresh: true, wantName: reporterAgentName, wantDescription: reporterAgentDescription},
		{name: "untouched", storedName: oldName, storedDescription: oldDescription, wantName: reporterAgentName, wantDescription: reporterAgentDescription},
		{name: "custom name", storedName: "我的报告员", storedDescription: oldDescription, wantName: "我的报告员", wantDescription: reporterAgentDescription},
		{name: "custom description", storedName: oldName, storedDescription: "自定义职责", wantName: reporterAgentName, wantDescription: "自定义职责"},
		{name: "both custom", storedName: "我的报告员", storedDescription: "自定义职责", wantName: "我的报告员", wantDescription: "自定义职责"},
		{name: "empty description", storedName: oldName, wantName: reporterAgentName},
		{name: "deleted", deleted: true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := pg.Exec(`TRUNCATE agents, settings, agent_prompts, agent_triggers, tools`); err != nil {
				t.Fatal(err)
			}
			if !tc.fresh {
				if err := pg.SetSetting("reporter_agent_seed_v1", "true"); err != nil {
					t.Fatal(err)
				}
			}
			if !tc.fresh && !tc.deleted {
				a, err := pg.CreateAgent("reporter", tc.storedName, tc.storedDescription)
				if err != nil {
					t.Fatal(err)
				}
				if _, err := pg.Exec(`UPDATE agents SET enabled=false, llm_profile_id=123, max_turns=7,
					wrapup_prompt='custom wrapup', trigger_run_mode='parallel', trigger_merge_mode='none',
					trigger_max_parallel=2 WHERE id=$1`, a.ID); err != nil {
					t.Fatal(err)
				}
				if err := pg.SeedPromptIfEmpty(a.ID, "custom prompt"); err != nil {
					t.Fatal(err)
				}
				if _, err := pg.CreateTrigger(&db.AgentTrigger{AgentKey: "reporter", Enabled: false,
					OnToolCall: true, ToolNames: []string{"report_finding"}, ToolCallMessage: "custom trigger"}); err != nil {
					t.Fatal(err)
				}
			}
			if _, err := pg.Exec(`INSERT INTO tools(key, agents) VALUES ('custom_report_tool', '["reporter", "unrelated"]')`); err != nil {
				t.Fatal(err)
			}
			if _, err := pg.CreateAgent("unrelated", oldName, oldDescription); err != nil {
				t.Fatal(err)
			}
			if err := pg.SetSetting("custom_setting", "preserve me"); err != nil {
				t.Fatal(err)
			}
			snapshot := func() string {
				t.Helper()
				var state string
				if err := pg.QueryRow(`SELECT jsonb_build_object(
					'agents', (SELECT jsonb_agg(CASE WHEN key='reporter' THEN to_jsonb(a)-'name'-'description' ELSE to_jsonb(a) END ORDER BY key) FROM agents a),
					'prompts', (SELECT jsonb_agg(to_jsonb(p) ORDER BY id) FROM agent_prompts p),
					'triggers', (SELECT jsonb_agg(to_jsonb(t) ORDER BY id) FROM agent_triggers t),
					'tools', (SELECT jsonb_agg(to_jsonb(t) ORDER BY key) FROM tools t),
					'settings', (SELECT jsonb_agg(to_jsonb(s) ORDER BY key) FROM settings s WHERE key<>'reporter_labels_zh_v1')
				)::text`).Scan(&state); err != nil {
					t.Fatal(err)
				}
				return state
			}
			s.seedReporterAgent()
			before := snapshot()
			s.upgradeReporterLabels()
			if after := snapshot(); after != before {
				t.Fatalf("migration modified data beyond reporter labels: before=%s after=%s", before, after)
			}
			a, err := pg.GetAgentByKey("reporter")
			if err != nil {
				t.Fatal(err)
			}
			if tc.deleted {
				if a != nil {
					t.Fatal("deleted reporter was recreated")
				}
			} else if a == nil || a.Name != tc.wantName || a.Description != tc.wantDescription {
				t.Fatalf("reporter labels: got %+v, want name=%q description=%q", a, tc.wantName, tc.wantDescription)
			}
			s.upgradeReporterLabels()
			again, err := pg.GetAgentByKey("reporter")
			if err != nil || !reflect.DeepEqual(a, again) || snapshot() != before {
				t.Fatalf("migration was not idempotent: reporter=%+v err=%v", again, err)
			}
			if v, ok, err := pg.GetSetting("reporter_labels_zh_v1"); err != nil || !ok || v != "true" {
				t.Fatalf("migration flag: value=%q exists=%v err=%v", v, ok, err)
			}
		})
	}
}
